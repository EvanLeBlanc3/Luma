"""Rebuild the dependency-free browser bundle after changing source modules."""
from pathlib import Path
import re
root=Path(__file__).resolve().parent
parts=[]
for name in ['filters.js','framing.js','pixels.js','renderer.js','app.js']:
 code=(root/name).read_text()
 code=re.sub(r'^import .*;\n','',code,flags=re.M)
 code=re.sub(r'^export ', '',code,flags=re.M)
 parts.append('// '+name+'\n'+code)
(root/'bundle.js').write_text("/* LeLuma 1.3.0 — generated by build.py */\n(()=>{\n'use strict';\n"+'\n'.join(parts)+'\n})();\n')
print('Built bundle.js')

worker=(root/'pixels.js').read_text().replace('export async function','async function')+'\n'+re.sub(r'^import .*;\n','',(root/'pixel-worker.js').read_text(),flags=re.M)
(root/'pixel-worker.bundle.js').write_text('/* LeLuma 1.3.0 filter worker */\n'+worker)
ids=re.findall(r"look\('([^']+)'",(root/'filters.js').read_text())
import json
sw=(root/'sw.js').read_text()
sw=re.sub(r'const FILTER_IDS=.*?;', 'const FILTER_IDS='+json.dumps(ids)+';',sw)
(root/'sw.js').write_text(sw)
print(str(len(ids)-1)+' filters + Original; bundled worker ready')
